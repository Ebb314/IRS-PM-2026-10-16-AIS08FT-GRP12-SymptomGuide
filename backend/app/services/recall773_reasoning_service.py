"""REASONING_MODE=recall773: teammate's full 773-disease tri-state recall model.

Reuses the DDXPlus-mode services (recall nucleus + confidence rule, GroupWork informed search,
PrimeKG drug relations); only the data layer differs. Mapping tables are generated by
scripts/build_recall773_mapping.py from the teammate's shared-KG catalog (data/recall773/).

  YES to a chatbot symptom -> the model symptom(s) it names; a broad KG term (e.g. "Chest pain")
                              maps to its group's representative ("sharp chest pain").
  NO  to a chatbot symptom -> the same, plus every subtype of a broad term ("no chest pain"
                              rules out sharp and burning chest pain).
  Not sure                 -> nothing is sent (tri-state "unknown").
Model-only symptoms (diarrhea, toothache, ...) have no precise KG node; they are added to the
chatbot vocabulary from data/recall773/extra_symptom_nodes.csv in this mode only.

Disease -> symptom table used to choose questions: DISEASE_SYMPTOM_TABLE (CSV with
disease,symptom,frequency, e.g. exported from the training data) when set (diseases it does not
cover keep the provisional entry); otherwise a provisional
table derived from the model (a symptom belongs to a disease when it alone gives that disease
>= 5x uniform probability; every disease keeps at least its strongest symptom).
"""
import csv
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Optional

import numpy as np

from app.services.ddxplus_reasoning_service import (
    DDXPlusDrugService, DDXPlusRecallService, DDXPlusSearchService,
)
from app.services.ddxplus_runtime import load_recall773_model
from app.services.kg_reasoning_service import KGDrugService, load_kg_data, load_symptom_whitelist

MAPPING_DIR = Path(__file__).resolve().parents[1] / "data" / "recall773"
EXTRA_NODES_FILE = MAPPING_DIR / "extra_symptom_nodes.csv"


class Recall773Data:
    id_prefix, id_width, source_tag, question_label = "DSA", 4, "recall773-tristate-v2", "Model symptom"

    def __init__(self, model, nodes: dict, table_file: Optional[str] = None, table_min_frequency=0.2):
        self.model = model
        self.kg_to_evidence: Dict[str, List[str]] = defaultdict(list)   # YES
        self.kg_to_absent: Dict[str, List[str]] = defaultdict(list)     # NO
        self.evidence_to_name: Dict[str, str] = {}                      # feature -> chatbot term to ask
        self.questions: Dict[str, List[str]] = defaultdict(list)
        with open(MAPPING_DIR / "feature_map.csv", encoding="utf-8", newline="") as f:
            rows = list(csv.DictReader(f))
        for row in rows:
            node = nodes.get(row["node_id"])
            if node is None or node.kg_name != row["node_name"]:
                raise ValueError(f"feature_map.csv: {row['feature']} -> {row['node_id']} is not in the chatbot "
                                 "vocabulary (recall773 mode loads data/recall773/extra_symptom_nodes.csv)")
            feature = row["feature"]
            self.kg_to_evidence[row["node_id"]].append(feature)
            self.kg_to_absent[row["node_id"]].append(feature)
            self.evidence_to_name[feature] = row["node_name"]
            if row["represents_head"]:
                self.kg_to_evidence[row["group_head_id"]].append(feature)
            if row["group_head_id"]:
                self.kg_to_absent[row["group_head_id"]].append(feature)
            if row["node_name"].casefold() != feature.casefold():
                self.questions[row["node_name"]].append(feature)
        self.primekg_name: Dict[str, str] = {}
        with open(MAPPING_DIR / "disease_map.csv", encoding="utf-8", newline="") as f:
            for row in csv.DictReader(f):
                if row["primekg_name"]:
                    self.primekg_name[row["disease"]] = row["primekg_name"]
        self.disease_index = {d: i for i, d in enumerate(model.diseases)}
        if table_file:
            self.disease_symptoms = self._from_table(table_file, table_min_frequency)
            self.table_source = "training-data-frequency"
        else:
            self.disease_symptoms, self.table_source = self._from_model(), "model-derived-provisional"

    def _from_model(self, factor=5.0):
        features = list(self.evidence_to_name)
        probs = np.stack([self.model.probabilities([f]) for f in features])        # features x diseases
        member = probs >= factor / len(self.model.diseases)
        member[probs.argmax(axis=0), np.arange(probs.shape[1])] = True              # >= 1 symptom each
        table = {}
        for j, disease in enumerate(self.model.diseases):
            table[disease] = sorted({self.evidence_to_name[features[i]] for i in np.flatnonzero(member[:, j])})
        return table

    def _from_table(self, path, min_frequency):
        table = defaultdict(set)
        with open(path, encoding="utf-8-sig", newline="") as f:
            for row in csv.DictReader(f):
                if row["disease"] in self.disease_index and row["symptom"] in self.evidence_to_name \
                        and float(row["frequency"]) >= min_frequency:
                    table[row["disease"]].add(self.evidence_to_name[row["symptom"]])
        if not table:
            raise ValueError("DISEASE_SYMPTOM_TABLE matched no model disease/symptom names")
        provisional = self._from_model()   # diseases the table does not cover keep the provisional entry
        return {d: sorted(table[d]) if d in table else provisional[d] for d in self.model.diseases}

    def evidence(self, symptoms):
        return sorted({f for s in symptoms for f in self.kg_to_evidence.get(s.kg_id, [])})

    def absent_evidence(self, symptoms):
        return sorted({f for s in symptoms for f in self.kg_to_absent.get(s.kg_id, [])})


def build_recall773_services(nodes: dict, kg_reasoning_file: str, top_k=10, mass=0.95, temperature=1.0,
                             per_disease=5, table_file: Optional[str] = None, whitelist_path: Optional[str] = None,
                             backend="auto", confident=0.8, variant=None):
    if all(k.startswith("DEMO:") for k in nodes):
        raise ValueError("REASONING_MODE=recall773 requires the full KG vocabulary (kg_nodes.csv), not the DEMO list.")
    data = Recall773Data(load_recall773_model(backend, variant), nodes, table_file or None)
    data.source_tag = f"recall773-tristate-v2-{data.model.variant}"
    kg = load_kg_data(str(kg_reasoning_file))
    return (DDXPlusRecallService(data, top_k, mass, temperature, False, confident),
            DDXPlusSearchService(data, nodes, load_symptom_whitelist(whitelist_path)),
            DDXPlusDrugService(data, KGDrugService(kg, per_disease)))
